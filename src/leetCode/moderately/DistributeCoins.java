package leetCode.moderately;

import leetCode.help.TreeNode;

/**
 * 979. 在二叉树中分配硬币
 *
 * 核心思路：净盈余 = 必须移动的次数，下界即最优。
 *
 * 题目关键约束：整棵树有 n 个节点，所有节点的硬币总数也恰好是 n，
 * 目标是让每个节点恰好有 1 枚硬币；且每次移动只能搬运 1 枚硬币到相邻节点。
 *
 * 推导过程：
 * 1. 把树沿任意一条边切开，分成"某一棵子树"与"它的外部"。
 * 2. 这棵子树最终需要的硬币数 = 它的节点数 N（每节点 1 枚）；
 *    它现在拥有的硬币数 = 子树内所有节点 val 之和 S。
 * 3. 净盈余 = S - N：正数表示多出的硬币必须送出去，负数表示缺的必须收进来。
 * 4. 硬币进出这棵子树，唯一能走的路就是"子树根与其父节点"之间那条边。
 *    由于一次只能搬 1 枚，这条边必须承载 |S - N| 次移动——这是绕不开的下界。
 * 5. 每条边各算各的下界并累加，即为最少移动次数（可按需调度达到该下界）。
 *
 * 实现：后序遍历自底向上汇总，返回"子树总硬币数、子树总节点数"，
 * 在每个父节点处累加左右子树的净盈余绝对值。
 * 根节点没有父边，因此根的净盈余不累加（在 dfs 入口处自然被忽略）。
 *
 * @author: gj
 */
public class DistributeCoins {

    /** 全局计数器：累加每条边必须发生的移动次数 */
    int res = 0;

    public int distributeCoins(TreeNode root) {
        dfs(root);
        return res;
    }

    /**
     * 后序遍历：先递归算完左右子树，再汇总出以 node 为根的整棵子树的信息。
     *
     * @param node 当前节点
     * @return int[2]：
     *         result[0] = 以 node 为根的子树中所有节点硬币总数（含 node 自身 val）
     *         result[1] = 以 node 为根的子树中节点总数（含 node 自身）
     */
    private int[] dfs(TreeNode node) {
        // 空节点：既没有硬币也没有节点
        if (node == null) {
            return new int[]{0, 0};
        }

        // 后序：先拿到左右子树的信息
        int[] l = dfs(node.left);
        int[] r = dfs(node.right);

        // 关键：净盈余 = 子树现有硬币数 - 子树需要的硬币数(节点数)
        // 左子树净盈余 = l[0] - l[1]，它必须穿过 node 与其左子之间的那条边，累加绝对值
        res += Math.abs(l[0] - l[1]);
        // 右子树净盈余 = r[0] - r[1]，它必须穿过 node 与其右子之间的那条边，累加绝对值
        res += Math.abs(r[0] - r[1]);

        // 汇总给父节点使用：
        // 总硬币数 = 自己身上的 val + 左子树硬币数 + 右子树硬币数
        // 总节点数 = 自己 1 个 + 左子树节点数 + 右子树节点数
        return new int[]{node.val + l[0] + r[0], 1 + l[1] + r[1]};
    }
}
