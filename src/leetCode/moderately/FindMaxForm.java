package leetCode.moderately;

/**
 * @description: 474. 一和零
 */
public class FindMaxForm {

    /*
     * 动态规划（01背包应用） 需要形成详细记录
     * 【问题定性】
     * 本题是一个“多维费用的 0/1 背包问题”。
     * 每个字符串就是一个物品，每个物品只能选一次，目标是在两种容量（0的个数、1的个数）限制下，
     * 最大化选取的物品数量。
     *
     * 【和 518. 零钱兑换 II 的本质区别】
     * 千万不要把本题和“零钱兑换 II”混淆！
     * - 零钱兑换（完全背包）：硬币无限量 -> 内层容量需要正序遍历（允许重复拿）。
     * - 本题（0/1背包）：字符串只有一份 -> 内层容量必须逆序遍历（防止重复拿）。
     * 二者的遍历顺序完全相反，这是这道题的第一个大坑。
     *
     * 【状态定义（dp 数组的含义）】
     * dp[i][j] = k
     * 表示：在“当前已经遍历过的前 n 个字符串”中，恰好使用 i 个 '0' 和 j 个 '1' 时，
     * 能够组成的最大字符串个数 k。
     * （注意：“前 n 个”这个阶段是由外层循环隐式提供的，每一轮循环代表一个新的决策阶段）
     *
     * 【状态转移方程】
     * 对于当前遍历到的字符串 s（设其中有 zeros 个 0，ones 个 1）：
     * dp[i][j] = max(dp[i][j], dp[i - zeros][j - ones] + 1)
     * 即：不选 s（保持原状） vs 选 s（腾出容量，个数+1）。
     *
     * 【为什么外层必须遍历字符串（物品）？】（沟通重点 1）
     * 外层循环代表“决策的时间轴”。
     * 只有把物品放在外层，程序才知道“截止到目前，我已经考虑完了前 k 个物品”。
     * 如果外层遍历容量，内层遍历物品，程序就会失去“已处理物品”的边界感，
     * 导致在计算不同容量格子时，会反复把同一个字符串拿来使用，完全乱套。
     *
     * 【为什么内层容量必须逆序（从大到小）遍历？】（沟通重点 2）
     * 这是 0/1 背包的“铁律”。
     * 逆序保证了在计算 dp[i][j] 时，所依赖的 dp[i-zeros][j-ones]
     * 依然停留在“上一个字符串（前 k-1 个）”的旧状态，还没有被本轮（第 k 个）更新过。
     *
     * 【深度答疑：逆序时，“后面的数据依赖前面”，但前面本轮没填，不会出问题吗？】
     * 完全不会！这里的“依赖”指的是依赖“上一轮（旧）的前面”，而不是“本轮（新）的前面”。
     * - 正序会先更新小容量，导致大容量计算时误用“本轮新数据”，相当于把同一个字符串用了多次。
     * - 逆序会先更新大容量，此时小容量还是旧的，完美避免了重复使用。这就是精妙之处！
     *
     * 【复杂度分析】
     * 时间复杂度：O(n * m * N)，其中 n 是字符串数量，m 是 0 的容量，N 是 1 的容量。
     * 空间复杂度：O(m * N)，使用了二维状态数组。
     * ============================================================
     */
    public int findMaxForm(String[] strs, int m, int n) {
        /**
         * dp[i][j] = k:表示当前物品（前n个字符串）下，组成i个n和j个1，最多能选出的字符串个数。
         */
        int[][] dp = new int[m + 1][n + 1];

        // 外层循环：遍历每一个字符串（决策阶段）
        for (String s : strs) {
            int zeros = 0, ones = 0;
            // 统计当前字符串的 0 和 1 的数量
            for (char c : s.toCharArray()) {
                if (c == '0') zeros++;
                else ones++;
            }

            // 内层循环：二维容量必须严格逆序（从大到小），避免正序遍历重复拿str
            // 确保每个字符串只能被选择一次
            for (int i = m; i >= zeros; i--) {
                for (int j = n; j >= ones; j--) {
                    // 状态转移：不选 vs 选
                    dp[i][j] = Math.max(dp[i][j], dp[i - zeros][j - ones] + 1);
                }
            }
        }
        return dp[m][n];
    }
}
